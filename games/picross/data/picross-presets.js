/**
 * Calculate hints for rows and columns from solution grid
 * @param {Array<Array<number>>} solution - 2D array of 0s and 1s
 * @returns {Object} - Object with rowHints and colHints arrays
 */
export function calculateHints(solution) {
    const size = solution.length;
    const rowHints = [];
    const colHints = [];
    
    // Calculate row hints
    for (let row = 0; row < size; row++) {
        const hints = [];
        let count = 0;
        for (let col = 0; col < size; col++) {
            if (solution[row][col] === 1) {
                count++;
            } else if (count > 0) {
                hints.push(count);
                count = 0;
            }
        }
        if (count > 0) hints.push(count);
        rowHints.push(hints.length > 0 ? hints : [0]);
    }
    
    // Calculate column hints
    for (let col = 0; col < size; col++) {
        const hints = [];
        let count = 0;
        for (let row = 0; row < size; row++) {
            if (solution[row][col] === 1) {
                count++;
            } else if (count > 0) {
                hints.push(count);
                count = 0;
            }
        }
        if (count > 0) hints.push(count);
        colHints.push(hints.length > 0 ? hints : [0]);
    }
    
    return { rowHints, colHints };
}
